let hello=1;
let world=0;

// and operator
console.log(hello==1 && world == 0);
console.log(hello==1 && world == 1);
console.log(hello==0 && world == 1);
console.log(hello==0 && world == 0);

// Or operator

let hello1=1;
let world1=1;

console.log(hello1==1 || world1 == 0);
console.log(hello1==1 || world1 == 1);
console.log(hello1==0 || world1 == 1);
console.log(hello1==0 || world1 == 0);


